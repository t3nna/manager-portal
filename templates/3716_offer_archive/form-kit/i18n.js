window.FormKitI18n.normalize = function (lang) {
    var raw = String(lang || "en")
        .trim()
        .toLowerCase()
        .replace(/_/g, "-");
    if (!raw) {
        return "en";
    }

    var aliases = {
        zh: "zh-CN",
        "zh-cn": "zh-CN",
        "zh-hans": "zh-CN",
        ch: "zh-CN",
        "zh-tw": "zh-TW",
        "zh-hant": "zh-TW",
        "pt-br": "pt-BR",
        ptbr: "pt-BR",
        "pt-pt": "pt-PT",
        ptpt: "pt-PT",
        se: "sv",
        "sv-se": "sv",
    };

    if (aliases[raw]) {
        return aliases[raw];
    }

    if (raw.indexOf("-") !== -1) {
        var parts = raw.split("-");
        return parts[0] + "-" + parts[1].toUpperCase();
    }

    return raw.slice(0, 2);
};

window.FormKitI18n.get = function (lang) {
    var code = window.FormKitI18n.normalize(lang);
    var defaults = window.FormKitI18n.en;
    return Object.assign({}, defaults, window.FormKitI18n[code] || defaults);
};

window.FormKitI18n.isRtl = function (lang) {
    var code = window.FormKitI18n.normalize(lang);
    return code === "ar" || code.indexOf("ar-") === 0;
};

