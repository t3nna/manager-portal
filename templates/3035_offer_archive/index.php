                        this.beginPath();
                        this.moveTo(x + r, y);
                        this.arcTo(x + w, y, x + w, y + h, r);
                        this.arcTo(x + w, y + h, x, y + h, r);
                        this.arcTo(x, y + h, x, y, r);
                        this.arcTo(x, y, x + w, y, r);
                        this.closePath();
                        return this;
                    };
                }

                function draw() {
                    const cfg = getConfig();
                    const W = canvas.width / dpr;
                    const H = canvas.height / dpr;
                    const PAD = cfg.padding;
                    const plotW = Math.max(W - PAD.l - PAD.r, 10);
                    const plotH = Math.max(H - PAD.t - PAD.b, 10);
                    ctx.clearRect(0, 0, W, H);

                    const yFor = (v) => PAD.t + plotH - ((v - 20) / (200 - 20)) * plotH;
                    const divider = Math.max(series[0].data.length - 1, 1);
                    const stepX = plotW / divider;

                    series.forEach((s) => {
                        ctx.strokeStyle = s.color;
                        ctx.lineWidth = s.name.includes("Marcos") ? cfg.lines.leader : cfg.lines.regular;
                        ctx.beginPath();

                        if (s.name.includes("Marcos")) {
                            ctx.shadowBlur = 14;
                            ctx.shadowColor = "rgba(250,204,21,0.7)";
                        } else {
                            ctx.shadowBlur = 0;
                        }

                        s.data.forEach((v, i) => {
                            const x = PAD.l + i * stepX;
                            const y = yFor(v);
                            if (i === 0) ctx.moveTo(x, y);
                            else ctx.lineTo(x, y);
                        });
                        ctx.stroke();
                        ctx.shadowBlur = 0;

                        const lastY = yFor(s.data[s.data.length - 1]);
                        const lastX = PAD.l + (s.data.length - 1) * stepX;
                        const flickerAlpha = s.name.includes("Marcos") ? 0.8 + 0.2 * Math.sin(Date.now() / 90) : 0.45;
                        ctx.fillStyle = `${s.color}${Math.round(flickerAlpha * 255)
                            .toString(16)
                            .padStart(2, "0")}`;
                        ctx.beginPath();
                        ctx.arc(lastX, lastY, s.name.includes("Marcos") ? cfg.points.leader : cfg.points.regular, 0, Math.PI * 2);
                        ctx.fill();

                        if (s.name.includes("Marcos")) {
                            const label = `${s.data[s.data.length - 1].toFixed(1)}%`;
                            ctx.font = cfg.labelFont;
                            const tw = ctx.measureText(label).width + 12;
                            const th = cfg.labelHeight;
                            ctx.fillStyle = "#facc15";
                            ctx.beginPath();
                            ctx.roundRect(lastX - tw / 2, lastY - th - cfg.labelOffset, tw, th, 8);
                            ctx.fill();
                            ctx.fillStyle = "#111827";
                            ctx.textAlign = "center";
                            ctx.textBaseline = "middle";
                            ctx.fillText(label, lastX, lastY - th / 2 - cfg.labelOffset);
                        }
                    });
                }

                function loop() {
                    draw();
                    requestAnimationFrame(loop);
                }

                loop();
                setInterval(updateData, 1500);
            })();
        </script>

